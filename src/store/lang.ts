export type MessageKey = keyof typeof messages.th;

// ── Reactive State ───────────────────────────────────────────────────────────
const STORAGE_KEY = 'vc_locale';

function detectLocale(): Locale {
  const saved = localStorage.getItem(STORAGE_KEY) as Locale | null;
  if (saved === 'th' || saved === 'en') return saved;
  return navigator.language.startsWith('th') ? 'th' : 'en';
}

export const langStore = reactive({
  locale: 'th' as Locale,

  init() {
    this.locale = detectLocale();
  },

  toggle() {
    this.locale = this.locale === 'th' ? 'en' : 'th';
    localStorage.setItem(STORAGE_KEY, this.locale);
  },

  setLocale(locale: Locale) {
    this.locale = locale;
    localStorage.setItem(STORAGE_KEY, locale);
  },

  /** Translate a key — reactive because `this.locale` is tracked */
  t(key: MessageKey): string {
    return (messages[this.locale] as any)[key]
      ?? (messages.th as any)[key]
      ?? key;
  },
});

/** Composable shorthand */
export function useLang() {
  return langStore;
}
